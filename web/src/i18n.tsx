const dictionaries: Record<Lang, Record<string, string>> = { ja, en };

export type TFunc = (key: string, params?: Record<string, unknown>) => string;

const I18n = createContext<{ lang: Lang; setLang: (l: Lang) => void; t: TFunc }>({
  lang: "ja",
  setLang: () => {},
  t: (k) => k,
});

function initialLang(): Lang {
  try {
    const saved = localStorage.getItem("kemomichi.lang");
    if (saved === "ja" || saved === "en") return saved;
  } catch {
    /* storage unavailable */
  }
  return navigator.language.toLowerCase().startsWith("ja") ? "ja" : "en";
}

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>(initialLang);
  const setLang = useCallback((l: Lang) => {
    setLangState(l);
    document.documentElement.lang = l;
    try {
      localStorage.setItem("kemomichi.lang", l);
    } catch {
      /* ignore */
    }
  }, []);
  const t = useCallback<TFunc>(
    (key, params) => {
      let text = dictionaries[lang][key] ?? dictionaries.ja[key] ?? key;
      for (const [k, v] of Object.entries(params ?? {})) text = text.split(`{${k}}`).join(String(v));
      return text;
    },
    [lang],
  );
  const value = useMemo(() => ({ lang, setLang, t }), [lang, setLang, t]);
  return <I18n.Provider value={value}>{children}</I18n.Provider>;
}

export const useI18n = () => useContext(I18n);
